/**
 * Generate `src/lib/clientRoster.ts` from the client's real export CSV.
 *
 * The demo build (NEXT_PUBLIC_DEMO_MODE=true) is credential-free and reads mock
 * data. To let the client POC verify their REAL salons/employees/numbers without
 * logging in, we bake the real roster into a committed data module that both
 * `mockData.ts` and `teamData.ts` build from.
 *
 * Re-run after the client sends a fresh export:
 *   node scripts/gen-client-roster.mjs "PPH Data 06-26-2026.xlsx.csv"
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const SRC = process.argv[2] ?? join(ROOT, "PPH Data 06-26-2026.xlsx.csv");
const OUT = join(ROOT, "src/lib/clientRoster.ts");

/** Minimal RFC-4180-ish CSV line splitter (handles quoted fields with commas). */
function splitCsvLine(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQuotes) {
      if (c === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        cur += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      out.push(cur);
      cur = "";
    } else {
      cur += c;
    }
  }
  out.push(cur);
  return out;
}

/** Parse messy currency like `_($* 2418.15_)`, `$1,234.56`, `2732.10`. */
function parseMoney(v) {
  if (v == null) return 0;
  const cleaned = String(v).replace(/[^0-9.\-]/g, "");
  const n = Number.parseFloat(cleaned);
  return Number.isFinite(n) ? n : 0;
}

function num(v) {
  const n = Number.parseFloat(String(v ?? "").replace(/[^0-9.\-]/g, ""));
  return Number.isFinite(n) ? n : 0;
}

const raw = readFileSync(SRC, "utf8").replace(/^\uFEFF/, "");
const lines = raw.split(/\r?\n/).filter((l) => l.trim().length > 0);
const header = splitCsvLine(lines[0]).map((h) => h.trim());
const col = (name) => header.findIndex((h) => h.toLowerCase() === name.toLowerCase());

const idx = {
  salon: col("Salon"),
  salonName: col("Salon Name"),
  code: col("Employee code"),
  name: col("Employee Name"),
  position: col("Position"),
  guarantee: col("Guaranteed Pay-Rate"),
  scheduled: col("Scheduled hours"),
  worked: col("Hours worked"),
  netRev: col("Net service Rev"),
  avgHaircut: col("Avg Haircut"),
  avgColor: col("Avg Color"),
};

/** Title-case a SHOUTY or mixed-case name for nicer display. */
function titleCase(s) {
  return s
    .trim()
    .toLowerCase()
    .replace(/\b([a-z])/g, (m) => m.toUpperCase());
}

const salonOrder = [];
const salonByCode = new Map();
const people = [];

for (const line of lines.slice(1)) {
  const cells = splitCsvLine(line);
  const salonCode = (cells[idx.salon] ?? "").trim();
  const salonName = (cells[idx.salonName] ?? "").trim() || salonCode;
  const employeeCode = (cells[idx.code] ?? "").trim();
  const name = titleCase((cells[idx.name] ?? "").trim());
  if (!salonCode || !employeeCode || !name) continue;

  if (!salonByCode.has(salonCode)) {
    const id = `s${salonOrder.length + 1}`;
    salonByCode.set(salonCode, { id, code: salonCode, name: salonName });
    salonOrder.push(salonCode);
  }
  const salon = salonByCode.get(salonCode);

  const position = (cells[idx.position] ?? "").trim().toLowerCase();
  const role = position.startsWith("manager") ? "manager" : "stylist";

  people.push({
    salonId: salon.id,
    salonCode,
    salonName: salon.name,
    employeeCode,
    name,
    role,
    guaranteeRate: num(cells[idx.guarantee]),
    scheduledHrs: num(cells[idx.scheduled]),
    actualHrs: num(cells[idx.worked]),
    netServiceRev: parseMoney(cells[idx.netRev]),
    avgHaircut: num(cells[idx.avgHaircut]) || 23,
    avgColor: num(cells[idx.avgColor]) || 85,
  });
}

const salons = salonOrder.map((code) => salonByCode.get(code));

// Deterministic avatar hue per person (stable across builds).
function hueFor(seed) {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0) % 360;
}

const peopleOut = people.map((p, i) => ({
  id: `u${i + 1}`,
  ...p,
  hue: hueFor(p.employeeCode + p.salonId),
}));

const banner = `// AUTO-GENERATED by scripts/gen-client-roster.mjs — do not edit by hand.
// Source: ${SRC.split("/").pop()} (the client's real roster + weekly performance).
// Re-run: node scripts/gen-client-roster.mjs "<csv path>"
`;

const body = `${banner}
export interface RosterSalon {
  /** Stable demo id (s1, s2, …). */
  id: string;
  /** The client's salon code, e.g. "11016-Burleson,TX-SSF". */
  code: string;
  /** Display name, e.g. "Burleson, TX". */
  name: string;
}

export interface RosterPerson {
  /** Stable demo id (u1, u2, …). */
  id: string;
  salonId: string;
  salonCode: string;
  salonName: string;
  /** The client's employee code, e.g. "VG1116". */
  employeeCode: string;
  name: string;
  role: "manager" | "stylist";
  guaranteeRate: number;
  scheduledHrs: number;
  actualHrs: number;
  netServiceRev: number;
  avgHaircut: number;
  avgColor: number;
  hue: number;
}

/** The pay week this export represents (Mon–Sun). */
export const CLIENT_WEEK_START = "2026-06-22";
export const CLIENT_WEEK_END = "2026-06-28";

export const CLIENT_SALONS: RosterSalon[] = ${JSON.stringify(salons, null, 2)};

export const CLIENT_ROSTER: RosterPerson[] = ${JSON.stringify(peopleOut, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`Wrote ${OUT}`);
console.log(`  salons: ${salons.length}`);
console.log(`  people: ${peopleOut.length} (${peopleOut.filter((p) => p.role === "manager").length} managers, ${peopleOut.filter((p) => p.role === "stylist").length} stylists)`);
