#!/usr/bin/env python3
"""Generate ``src/lib/clientDaily.ts`` from the client's real DAILY export.

The client provides one row per employee per work day. This script parses that
workbook and emits a typed TS module with the real per-day numbers (keyed by
employee code, hyphen stripped) plus the Include/Exclude flag, so the demo can
render the client's real daily data instead of synthesising days from weekly
aggregates.

A handful of employees work at two salons. Their rows carry the salon they were
worked at, so the days are ALSO emitted per ``code|salon`` — the roster lists
such a person once per location, and without the split both entries would show
(and the team roll-up would count) the same production twice.

Usage:
    python3 scripts/gen_client_daily.py "v2.PPH Data 06-22-2026 TO 07-05-2026.xlsx"
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

from openpyxl import load_workbook

# The same workbook arrives under either name — a browser download of a second
# copy appends " (2)".
DEFAULT_SRCS = (
    "v2.PPH Data 06-22-2026 TO 07-05-2026.xlsx",
    "v2.PPH Data 06-22-2026 TO 07-05-2026 (2).xlsx",
)
OUT = Path("src/lib/clientDaily.ts")


def norm_code(raw: object) -> str:
    return str(raw or "").replace("-", "").replace(" ", "").strip().upper()


def norm_salon(raw: object) -> str:
    """Salon display names differ in punctuation between the client's files
    ("Casper, 2nd St,WY" vs the roster's "Casper 2nd St,WY"), so compare on
    letters and digits only."""
    return "".join(ch for ch in str(raw or "").lower() if ch.isalnum())


def to_iso(raw: object) -> str | None:
    if raw is None or raw == "":
        return None
    if isinstance(raw, datetime):
        return raw.date().isoformat()
    if isinstance(raw, date):
        return raw.isoformat()
    s = str(raw).strip()
    for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%m/%d/%y", "%m-%d-%Y"):
        try:
            return datetime.strptime(s[:10] if fmt == "%Y-%m-%d" else s, fmt).date().isoformat()
        except ValueError:
            continue
    return None


def num(raw: object) -> float:
    if raw is None or raw == "":
        return 0.0
    try:
        return float(str(raw).replace("$", "").replace(",", "").strip())
    except ValueError:
        return 0.0


def monday_of(iso: str) -> str:
    d = date.fromisoformat(iso)
    return (d - timedelta(days=d.weekday())).isoformat()


def main() -> None:
    if len(sys.argv) > 1:
        src = Path(sys.argv[1])
    else:
        src = next((p for p in map(Path, DEFAULT_SRCS) if p.exists()), Path(DEFAULT_SRCS[0]))
    wb = load_workbook(src, read_only=True, data_only=True)
    rows = list(wb.active.iter_rows(values_only=True))[1:]

    daily: dict[str, list[dict]] = defaultdict(list)
    by_salon: dict[str, list[dict]] = defaultdict(list)
    exclude: dict[str, bool] = {}
    exclude_by_salon: dict[str, bool] = {}
    names: dict[str, str] = {}
    salons_per_code: dict[str, set[str]] = defaultdict(set)
    week_starts: set[str] = set()

    for r in rows:
        if not r or r[0] in (None, ""):
            continue
        code = norm_code(r[0])
        iso = to_iso(r[2])
        if not code or not iso:
            continue
        salon = norm_salon(r[1])
        excluded = str(r[10] or "").strip().lower() in {"exclude", "excluded", "y", "yes", "true", "1"}
        record = {
            "date": iso,
            "scheduledHours": round(num(r[3]), 2),
            "workedHours": round(num(r[4]), 2),
            "haircuts": int(round(num(r[5]))),
            "colors": int(round(num(r[6]))),
            "production": round(num(r[7]), 2),
        }
        week_starts.add(monday_of(iso))
        daily[code].append(record)
        by_salon[f"{code}|{salon}"].append(record)
        salons_per_code[code].add(salon)
        names[code] = str(r[8] or "").strip()
        exclude[code] = excluded
        exclude_by_salon[f"{code}|{salon}"] = excluded

    for records in (*daily.values(), *by_salon.values()):
        records.sort(key=lambda d: d["date"])

    multi_salon = sorted(code for code, salons in salons_per_code.items() if len(salons) > 1)

    header = (
        "// AUTO-GENERATED by scripts/gen_client_daily.py — do not edit by hand.\n"
        f"// Source: {src.name} (the client's real per-day export).\n"
        f"// {len(daily)} employees · {sum(len(v) for v in daily.values())} day rows · "
        f"weeks {sorted(week_starts)}.\n\n"
    )
    body = (
        "export interface ClientDailyRecord {\n"
        "  /** ISO work date (yyyy-mm-dd). */\n"
        "  date: string;\n"
        "  scheduledHours: number;\n"
        "  workedHours: number;\n"
        "  haircuts: number;\n"
        "  colors: number;\n"
        "  /** Authoritative daily service revenue from the export. */\n"
        "  production: number;\n"
        "}\n\n"
        "/** Real daily records keyed by employee code (hyphen stripped, e.g. VG1426). */\n"
        f"export const CLIENT_DAILY: Record<string, ClientDailyRecord[]> = {json.dumps(daily, indent=2)};\n\n"
        "/**\n"
        " * The same records keyed by `CODE|salon` (salon lowercased, letters and\n"
        " * digits only). Use this for anyone in CLIENT_DAILY_MULTI_SALON so each of\n"
        " * their roster entries only carries the days worked at that location.\n"
        " */\n"
        "export const CLIENT_DAILY_BY_SALON: Record<string, ClientDailyRecord[]> = "
        f"{json.dumps(by_salon, indent=2)};\n\n"
        "/** Employee codes that appear at more than one salon in the export. */\n"
        f"export const CLIENT_DAILY_MULTI_SALON: string[] = {json.dumps(multi_salon)};\n\n"
        "/** Include/Exclude from the file — true = excluded from the PPH pay plan. */\n"
        f"export const CLIENT_DAILY_EXCLUDE: Record<string, boolean> = {json.dumps(exclude, indent=2)};\n\n"
        "/** Include/Exclude per `CODE|salon` — it can differ between locations. */\n"
        "export const CLIENT_DAILY_EXCLUDE_BY_SALON: Record<string, boolean> = "
        f"{json.dumps(exclude_by_salon, indent=2)};\n\n"
        "/** Employee display names from the file (for reference). */\n"
        f"export const CLIENT_DAILY_NAMES: Record<string, string> = {json.dumps(names, indent=2)};\n\n"
        "/** Monday week-starts covered by the real daily data. */\n"
        f"export const CLIENT_DAILY_WEEK_STARTS: string[] = {json.dumps(sorted(week_starts))};\n"
    )
    OUT.write_text(header + body)
    print(
        f"Wrote {OUT} — {len(daily)} employees, weeks {sorted(week_starts)}"
        + (f", multi-salon: {multi_salon}" if multi_salon else "")
    )


if __name__ == "__main__":
    main()
