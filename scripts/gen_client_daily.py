#!/usr/bin/env python3
"""Generate ``src/lib/clientDaily.ts`` from the client's real DAILY export.

The client provides one row per employee per work day. This script parses that
workbook and emits a typed TS module with the real per-day numbers (keyed by
employee code, hyphen stripped) plus the Include/Exclude flag, so the demo can
render the client's real daily data instead of synthesising days from weekly
aggregates.

Usage:
    python3 scripts/gen_client_daily.py "v2.PPH Data 06-22-2026 TO 07-05-2026.xlsx"
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

from openpyxl import load_workbook

DEFAULT_SRC = "v2.PPH Data 06-22-2026 TO 07-05-2026.xlsx"
OUT = Path("src/lib/clientDaily.ts")


def norm_code(raw: object) -> str:
    return str(raw or "").replace("-", "").replace(" ", "").strip().upper()


def to_iso(raw: object) -> str | None:
    if raw is None or raw == "":
        return None
    if isinstance(raw, datetime):
        return raw.date().isoformat()
    if isinstance(raw, date):
        return raw.isoformat()
    s = str(raw).strip()
    for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%m/%d/%y", "%m-%d-%Y"):
        try:
            return datetime.strptime(s[:10] if fmt == "%Y-%m-%d" else s, fmt).date().isoformat()
        except ValueError:
            continue
    return None


def num(raw: object) -> float:
    if raw is None or raw == "":
        return 0.0
    try:
        return float(str(raw).replace("$", "").replace(",", "").strip())
    except ValueError:
        return 0.0


def monday_of(iso: str) -> str:
    d = date.fromisoformat(iso)
    return (d - timedelta(days=d.weekday())).isoformat()


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC)
    wb = load_workbook(src, read_only=True, data_only=True)
    rows = list(wb.active.iter_rows(values_only=True))[1:]

    daily: dict[str, list[dict]] = defaultdict(list)
    exclude: dict[str, bool] = {}
    names: dict[str, str] = {}
    week_starts: set[str] = set()

    for r in rows:
        if not r or r[0] in (None, ""):
            continue
        code = norm_code(r[0])
        iso = to_iso(r[2])
        if not code or not iso:
            continue
        week_starts.add(monday_of(iso))
        daily[code].append(
            {
                "date": iso,
                "scheduledHours": round(num(r[3]), 2),
                "workedHours": round(num(r[4]), 2),
                "haircuts": int(round(num(r[5]))),
                "colors": int(round(num(r[6]))),
                "production": round(num(r[7]), 2),
            }
        )
        names[code] = str(r[8] or "").strip()
        exclude[code] = str(r[10] or "").strip().lower() in {"exclude", "excluded", "y", "yes", "true", "1"}

    for code in daily:
        daily[code].sort(key=lambda d: d["date"])

    header = (
        "// AUTO-GENERATED by scripts/gen_client_daily.py — do not edit by hand.\n"
        f"// Source: {src.name} (the client's real per-day export).\n"
        f"// {len(daily)} employees · {sum(len(v) for v in daily.values())} day rows · "
        f"weeks {sorted(week_starts)}.\n\n"
    )
    body = (
        "export interface ClientDailyRecord {\n"
        "  /** ISO work date (yyyy-mm-dd). */\n"
        "  date: string;\n"
        "  scheduledHours: number;\n"
        "  workedHours: number;\n"
        "  haircuts: number;\n"
        "  colors: number;\n"
        "  /** Authoritative daily service revenue from the export. */\n"
        "  production: number;\n"
        "}\n\n"
        "/** Real daily records keyed by employee code (hyphen stripped, e.g. VG1426). */\n"
        f"export const CLIENT_DAILY: Record<string, ClientDailyRecord[]> = {json.dumps(daily, indent=2)};\n\n"
        "/** Include/Exclude from the file — true = excluded from the PPH pay plan. */\n"
        f"export const CLIENT_DAILY_EXCLUDE: Record<string, boolean> = {json.dumps(exclude, indent=2)};\n\n"
        "/** Employee display names from the file (for reference). */\n"
        f"export const CLIENT_DAILY_NAMES: Record<string, string> = {json.dumps(names, indent=2)};\n\n"
        "/** Monday week-starts covered by the real daily data. */\n"
        f"export const CLIENT_DAILY_WEEK_STARTS: string[] = {json.dumps(sorted(week_starts))};\n"
    )
    OUT.write_text(header + body)
    print(f"Wrote {OUT} — {len(daily)} employees, weeks {sorted(week_starts)}")


if __name__ == "__main__":
    main()
